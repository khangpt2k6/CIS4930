#!/usr/bin/env python3
"""Assemble report/final_report.md from the team's section files.

Run from the repository root or from report/:   python report/build_final_report.py

Inputs (all in report/):
  final/01_introduction.md, final/02_related_work.md, final/03_setup.md   front matter
  objective1_*.md ... objective5_*.md                                     one file per objective, written by its owner
  final/90_conclusion.md, final/99_references.md                          end matter
An objective with no file gets a clearly marked placeholder, so the report always builds.
Each objective file starts with "# Objective N: ..." and uses "## N.x" subsections; they are demoted one level here.
A subsection titled "N.x Limitations" in the Objective 4 file becomes the report's Limitations section.
This script only reads the section files; it never edits them. It overwrites final_report.md only.
"""
import glob, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
OBJECTIVES = {
    1: ("Lookup performance",
        "Average and p99 lookup latency and throughput of RMI, PGM-index, RadixSpline, B+tree, hash table and binary "
        "search in SOSD on books, fb, osm and wiki (200M keys)."),
    2: ("Memory vs. speed",
        "Lookup latency against index size for each index at several size settings on the four datasets; one plot per "
        "dataset, log-scale size axis."),
    3: ("Hardware counters",
        "Last-level cache misses, branch misses and instructions per lookup with `perf` on native Linux, at an "
        "in-cache size and at 200M keys, to explain Objectives 1 and 2."),
    4: ("Where learned indexes fall short", ""),
    5: ("Effect of modern hardware", ""),
}
PRELIMINARY = {
    1: "Available input: preliminary ARM64 SOSD lookups on 1M lognormal keys (no p99; RMI not in the ARM64 port), "
       "`sosd-arm64/runs/20261125-100608-release/summary/lookup_default.csv`; see `sosd-arm64/FOR_TEAM.md`.",
    2: "Available input: ARM64 latency-vs-size sweep for RadixSpline, PGM-index and B+tree on 1M lognormal keys, "
       "`sosd-arm64/runs/20261125-100608-release/summary/lookup_pareto.csv`; see `sosd-arm64/FOR_TEAM.md`.",
    3: "Not measurable on the Apple laptop (no `perf` on macOS; the Linux VM exposes no hardware counters). "
       "Needs a native Linux x86 machine.",
}


def read(rel):
    with open(os.path.join(HERE, rel), encoding="utf-8") as f:
        return f.read().strip() + "\n"


def demote(text):
    return re.sub(r"^(#+) ", lambda m: "#" + m.group(1) + " ", text, flags=re.M)


def split_limitations(text):
    m = re.search(r"^### \d+\.\d+ Limitations\s*$", text, flags=re.M)
    if not m:
        return text, ""
    return text[:m.start()].rstrip() + "\n", text[m.end():].strip() + "\n"


def main():
    parts = ["# Do Learned Indexes Still Win on Modern Hardware?\n",
             "*CIS 4930 Final Project, Team 01: Riyon Praveen, Vishakha Tiwari, Sevara Badriddinova, Tuan Khang Phan*\n",
             "> **Build note:** generated by `report/build_final_report.py`; edit the section files, not this file. "
             "Text marked [TODO] or [PLACEHOLDER] is not final.\n",
             read("final/01_introduction.md"), read("final/02_related_work.md"), read("final/03_setup.md")]
    limitations = ""
    for k, (title, scope) in OBJECTIVES.items():
        files = sorted(glob.glob(os.path.join(HERE, f"objective{k}_*.md")))
        if files:
            body = demote(read(os.path.relpath(files[0], HERE)))
            if k == 4:
                body, limitations = split_limitations(body)
            parts.append(body)
        else:
            parts.append(f"## Objective {k}: {title}\n\n> **[PLACEHOLDER: Objective {k} owner]** Add "
                         f"`report/objective{k}_<topic>.md` (start it with `# Objective {k}: ...`) and rerun this script.\n>\n"
                         f"> Scope: {scope}\n>\n> {PRELIMINARY[k]}\n")
    parts.append("## Limitations\n\n" + (limitations or "[TODO]\n"))
    parts += [read("final/90_conclusion.md"), read("final/99_references.md")]
    out = os.path.join(HERE, "final_report.md")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(parts))
    print("wrote", out)


if __name__ == "__main__":
    main()
